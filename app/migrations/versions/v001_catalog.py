"""001: справочники владельцев, лошадей, жокеев и состязаний."""

import psycopg


def upgrade(connection: psycopg.Connection) -> None:
    connection.execute(
        """
        CREATE TABLE app_metadata (
            key TEXT PRIMARY KEY,
            value TEXT NOT NULL
        )
        """
    )
    connection.execute(
        """
        CREATE TABLE owners (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            name TEXT NOT NULL CHECK (length(trim(name)) > 0),
            contact TEXT
        )
        """
    )
    connection.execute(
        """
        CREATE TABLE horses (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            name TEXT NOT NULL CHECK (length(trim(name)) > 0),
            birth_date DATE NOT NULL,
            breed TEXT NOT NULL CHECK (length(trim(breed)) > 0),
            owner_id BIGINT NOT NULL REFERENCES owners(id) ON DELETE RESTRICT
        )
        """
    )
    connection.execute(
        """
        CREATE TABLE jockeys (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            full_name TEXT NOT NULL CHECK (length(trim(full_name)) > 0),
            birth_date DATE NOT NULL,
            weight_kg DOUBLE PRECISION NOT NULL CHECK (weight_kg > 0)
        )
        """
    )
    connection.execute(
        """
        CREATE TABLE competitions (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            name TEXT NOT NULL CHECK (length(trim(name)) > 0),
            event_date DATE NOT NULL,
            location TEXT NOT NULL CHECK (length(trim(location)) > 0),
            distance_m INTEGER NOT NULL CHECK (distance_m > 0),
            status TEXT NOT NULL DEFAULT 'planned'
                CHECK (status IN ('planned', 'ongoing', 'completed', 'cancelled'))
        )
        """
    )
