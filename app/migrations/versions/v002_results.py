"""002: результаты и ограничения уникальности в состязании."""

import psycopg


def upgrade(connection: psycopg.Connection) -> None:
    connection.execute(
        """
        CREATE TABLE results (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            competition_id BIGINT NOT NULL
                REFERENCES competitions(id) ON DELETE RESTRICT,
            horse_id BIGINT NOT NULL REFERENCES horses(id) ON DELETE RESTRICT,
            jockey_id BIGINT NOT NULL REFERENCES jockeys(id) ON DELETE RESTRICT,
            position INTEGER NOT NULL CHECK (position > 0),
            time_seconds DOUBLE PRECISION NOT NULL CHECK (time_seconds > 0),
            disqualified BOOLEAN NOT NULL DEFAULT FALSE,
            disqualification_reason TEXT,
            UNIQUE (competition_id, horse_id),
            UNIQUE (competition_id, jockey_id),
            CHECK (
                (NOT disqualified AND disqualification_reason IS NULL)
                OR
                (disqualified AND length(trim(disqualification_reason)) > 0)
            )
        )
        """
    )
    connection.execute(
        """
        CREATE UNIQUE INDEX uq_results_competition_position
            ON results (competition_id, position)
            WHERE NOT disqualified
        """
    )
