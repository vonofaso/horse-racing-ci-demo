"""003: пользователи, сессии и индексы авторизации."""

import psycopg


def upgrade(connection: psycopg.Connection) -> None:
    connection.execute(
        """
        CREATE TABLE users (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            username TEXT NOT NULL CHECK (length(trim(username)) >= 3),
            email TEXT NOT NULL CHECK (length(trim(email)) > 0),
            password_hash TEXT NOT NULL,
            created_at TIMESTAMPTZ NOT NULL
        )
        """
    )
    connection.execute(
        "CREATE UNIQUE INDEX uq_users_username_lower ON users (lower(username))"
    )
    connection.execute(
        "CREATE UNIQUE INDEX uq_users_email_lower ON users (lower(email))"
    )
    connection.execute(
        """
        CREATE TABLE user_sessions (
            id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
            user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
            token_hash TEXT NOT NULL UNIQUE,
            created_at TIMESTAMPTZ NOT NULL,
            expires_at TIMESTAMPTZ NOT NULL
        )
        """
    )
    connection.execute(
        "CREATE INDEX ix_user_sessions_user_id ON user_sessions (user_id)"
    )
    connection.execute(
        "CREATE INDEX ix_user_sessions_expires_at ON user_sessions (expires_at)"
    )
    connection.execute(
        "INSERT INTO app_metadata (key, value) VALUES ('schema_version', '4')"
    )
